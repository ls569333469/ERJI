const {readFileSync}=require('node:fs');
const ts=require('typescript');
const {runInNewContext}=require('node:vm');
const assert=require('node:assert/strict');
const source=ts.transpileModule(readFileSync('apps/web/src/lib/opportunity-display.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText;
const output={};runInNewContext(source,{exports:output});
const {priceText,readableReason}=output;
assert.equal(priceText('0.034862341234','0.00001000'),'0.03486');
assert.equal(priceText('0.034865','0.00001'),'0.03487');
assert.equal(priceText('1.234','0.05'),'1.25');
assert.equal(priceText('0.0000000000123456','0.00000000000001'),'0.00000000001235');
assert.equal(priceText('12345678901234567890.124','0.01'),'12,345,678,901,234,567,890.12');
assert.equal(priceText(null),'—');assert.equal(priceText('NaN'),'—');
assert.equal(priceText('0.034862341234'),'0.0348623');
assert.equal(readableReason('触发 0.034862341234，量能 1.50 倍'),'触发 0.0348623，量能 1.50 倍');
console.log('price display: tiny ticks, non-power-of-ten ticks, exact decimals and missing values passed');
const {opportunityAdvice}=output;
const row={action_code:'waiting',reason:'actual',box:{trigger_price:'.02685'},tick_size:'.00001',pending_volume_multiple:'.97',trigger_requirements:{relative_volume_min:'1.5'}};
assert.match(opportunityAdvice(row).summary,/0.02685.*1.50.*0.97/);
assert.equal(opportunityAdvice({...row,pending_state:'intrabar_above_close_rejected'}).action,'盘中越线，收盘未站稳');
assert.equal(opportunityAdvice({...row,action_code:'paused',reason:'数据过期'}).summary,'数据过期');
assert.notEqual(opportunityAdvice(row).summary,opportunityAdvice({...row,box:{trigger_price:'.2483'}}).summary);
